export function personaPools(pack: PersonaPack, task?: TaskContext): LinePools {
  const pools = { ...pack.pools }
  const scene = taskLinesFor(pack, task)
  // Specific context enriches the voice instead of reducing it to two repeated lines.
  if (scene.length) for (const bucket of ['happy', 'busy', 'planning'] as const) pools[bucket] = [...new Set([...scene, ...pack.pools[bucket] ?? []])]
  return pools
}

/** Rotate between specific cues and the deliverable instead of exhausting one cue first. */
export function interleave(groups: readonly (readonly string[])[]): string[] {
  const out = new Set<string>()
  for (let i = 0; i < Math.max(0, ...groups.map(group => group.length)); i++) {
    for (const group of groups) if (group[i]) out.add(group[i])
  }
  return [...out]
}

export function taskLinesFor(pack: PersonaPack, task?: TaskContext): string[] {
  return task ? interleave([...task.signals.map(s => pack.signals[s] ?? []), pack.scenes[task.scenario] ?? []]) : []
}
